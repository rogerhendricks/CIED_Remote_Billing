import React, { useState } from 'react';
import { PatientRecord } from '../types';
import { BILLING_CODES, VENDOR_PORTALS } from '../data/billingCodes';
import { 
  Mail, 
  X, 
  Copy, 
  Download, 
  ExternalLink, 
  ShieldCheck, 
  AlertTriangle, 
  Check, 
  Send
} from 'lucide-react';

interface OutlookEmailModalProps {
  records: PatientRecord[];
  onClose: () => void;
  onMarkAsBilled: (ids: string[]) => void;
}

export const OutlookEmailModal: React.FC<OutlookEmailModalProps> = ({
  records,
  onClose,
  onMarkAsBilled
}) => {
  const [recipient, setRecipient] = useState<string>('billing@practice.com.au');
  const [ccRecipient, setCcRecipient] = useState<string>('cardiology-admin@practice.com.au');
  const [privacyMode, setPrivacyMode] = useState<boolean>(false);
  const [copied, setCopied] = useState<boolean>(false);

  // Group stats
  const totalRecords = records.length;
  const totalAud = records.reduce((acc, r) => acc + (BILLING_CODES[r.billingCode]?.mbsFeeAud || 0), 0);

  const subject = `Remote Cardiac Device Monitoring Billing Batch - ${new Date().toLocaleDateString('en-AU')} (${totalRecords} patients)`;

  // Generate plain text for mailto
  const buildPlainTextBody = () => {
    let body = `Dear Billing Team,\r\n\r\nPlease find below the remote cardiac device monitoring log for processing under Medicare (MBS):\r\n\r\n`;
    body += `Batch Date: ${new Date().toLocaleDateString('en-AU')}\r\n`;
    body += `Total Patients: ${totalRecords}\r\n`;
    body += `Estimated Total MBS Fee: $${totalAud.toFixed(2)} AUD\r\n\r\n`;
    body += `------------------------------------------------------------\r\n`;
    body += `PATIENT & BILLING LIST:\r\n`;
    body += `------------------------------------------------------------\r\n\r\n`;

    records.forEach((r, idx) => {
      const patientDisplay = privacyMode ? `Patient ID: ${r.patientIdOrMrn}` : `${r.patientName} (ID: ${r.patientIdOrMrn}${r.patientDob ? `, DOB: ${r.patientDob}` : ''})`;
      body += `${idx + 1}. ${patientDisplay}\r\n`;
      body += `   Portal: ${VENDOR_PORTALS[r.vendor]?.name || r.vendor}\r\n`;
      body += `   Device: ${r.deviceModel} (SN: ${r.deviceSerial})\r\n`;
      body += `   Transmission Date: ${r.transmissionDate} | Visited: ${r.visitDate}\r\n`;
      body += `   MBS Item: ${r.billingCode} ($${BILLING_CODES[r.billingCode]?.mbsFeeAud || 0} AUD)\r\n`;
      body += `   Clinician/Reviewer: ${r.loggedBy}\r\n`;
      if (r.clinicalFindings) {
        body += `   Notes: ${r.clinicalFindings}\r\n`;
      }
      body += `\r\n`;
    });

    body += `------------------------------------------------------------\r\n`;
    body += `Generated by Cardiac Remote Monitoring Hub\r\n`;
    return body;
  };

  const plainTextBody = buildPlainTextBody();

  const handleOpenOutlookMailto = () => {
    const encodedSubject = encodeURIComponent(subject);
    const encodedBody = encodeURIComponent(plainTextBody);
    const mailtoUrl = `mailto:${recipient}?cc=${ccRecipient}&subject=${encodedSubject}&body=${encodedBody}`;
    window.open(mailtoUrl, '_blank');
    onMarkAsBilled(records.map(r => r.id));
  };

  const handleCopyClipboard = () => {
    navigator.clipboard.writeText(plainTextBody);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  // Generate .eml file for direct desktop Outlook opening
  const handleDownloadEml = () => {
    const emlContent = 
`From: "Cardiac Monitoring Team" <cardio-monitoring@practice.com.au>
To: ${recipient}
Cc: ${ccRecipient}
Subject: ${subject}
MIME-Version: 1.0
Content-Type: text/plain; charset=UTF-8

${plainTextBody}
`;

    const blob = new Blob([emlContent], { type: 'message/rfc822' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Cardiac_Billing_Batch_${new Date().toISOString().slice(0,10)}.eml`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    onMarkAsBilled(records.map(r => r.id));
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs animate-fadeIn">
      <div className="bg-white rounded-2xl shadow-2xl border border-slate-200 w-full max-w-3xl max-h-[90vh] flex flex-col overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200 bg-slate-50">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-blue-100 text-blue-700">
              <Mail className="w-5 h-5" />
            </div>
            <div>
              <h3 className="font-bold text-slate-900 text-base">Prepare Outlook Billing Email</h3>
              <p className="text-xs text-slate-500">Dispatch selected {totalRecords} patient records to your practice billing email.</p>
            </div>
          </div>
          <button 
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-600 hover:bg-slate-200 transition-all cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-5 flex-1 text-xs sm:text-sm">
          {/* Privacy Protection Toggle */}
          <div className="flex items-center justify-between p-3.5 bg-blue-50/70 border border-blue-200 rounded-xl">
            <div className="flex items-center gap-2.5">
              <ShieldCheck className="w-5 h-5 text-blue-600 shrink-0" />
              <div>
                <span className="font-bold text-slate-900 text-xs block">Privacy Mode: De-Identify Patient Names in Email</span>
                <span className="text-[11px] text-slate-500 block">
                  Replaces patient names with Clinic Patient ID / MRN only to comply with unencrypted email privacy regulations.
                </span>
              </div>
            </div>
            <label className="relative inline-flex items-center cursor-pointer shrink-0 ml-3">
              <input 
                type="checkbox" 
                checked={privacyMode} 
                onChange={(e) => setPrivacyMode(e.target.checked)}
                className="sr-only peer"
              />
              <div className="w-10 h-5 bg-slate-300 peer-focus:outline-none rounded-full peer peer-checked:after:translate-x-full peer-checked:after:border-white after:content-[''] after:absolute after:top-[2px] after:left-[2px] after:bg-white after:border-slate-300 after:border after:rounded-full after:h-4 after:w-4 after:transition-all peer-checked:bg-blue-600"></div>
            </label>
          </div>

          {/* Email Settings */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
            <div>
              <label className="block font-semibold text-slate-700 mb-1">To (Billing Clerk / Department):</label>
              <input 
                type="email" 
                value={recipient} 
                onChange={(e) => setRecipient(e.target.value)}
                className="w-full bg-white border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
              />
            </div>
            <div>
              <label className="block font-semibold text-slate-700 mb-1">Cc (Admin / Cardiologist):</label>
              <input 
                type="email" 
                value={ccRecipient} 
                onChange={(e) => setCcRecipient(e.target.value)}
                className="w-full bg-white border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
              />
            </div>
          </div>

          {/* Batch Summary Stats */}
          <div className="grid grid-cols-3 gap-3 p-3 bg-slate-50 rounded-xl border border-slate-200 text-center">
            <div>
              <div className="text-xs text-slate-500 font-medium">Patients in Batch</div>
              <div className="text-lg font-bold text-slate-900">{totalRecords}</div>
            </div>
            <div>
              <div className="text-xs text-slate-500 font-medium">Est. Medicare Total</div>
              <div className="text-lg font-bold text-emerald-600">${totalAud.toFixed(2)} AUD</div>
            </div>
            <div>
              <div className="text-xs text-slate-500 font-medium">Subject Preview</div>
              <div className="text-xs font-semibold text-slate-700 truncate mt-1">{subject}</div>
            </div>
          </div>

          {/* Email Body Preview */}
          <div className="space-y-1.5">
            <div className="flex items-center justify-between">
              <label className="font-semibold text-slate-700 text-xs">Generated Outlook Message Body:</label>
              <button 
                onClick={handleCopyClipboard}
                className="text-xs text-blue-600 hover:text-blue-800 font-semibold flex items-center gap-1 cursor-pointer"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                {copied ? 'Copied to Clipboard!' : 'Copy Body Text'}
              </button>
            </div>
            <textarea
              readOnly
              rows={8}
              value={plainTextBody}
              className="w-full font-mono text-[11px] p-3 rounded-lg bg-slate-900 text-slate-200 border border-slate-700 select-all leading-relaxed"
            />
          </div>
        </div>

        {/* Footer Actions */}
        <div className="flex flex-col sm:flex-row items-center justify-between gap-3 px-6 py-4 border-t border-slate-200 bg-slate-50">
          <div className="text-xs text-slate-500 text-center sm:text-left">
            Choosing "Open Outlook Client" launches your desktop/web Outlook with pre-filled content.
          </div>
          <div className="flex items-center gap-2 w-full sm:w-auto">
            <button
              onClick={handleDownloadEml}
              title="Download an .eml draft file that opens natively in Microsoft Outlook desktop"
              className="flex-1 sm:flex-none px-4 py-2 rounded-lg bg-white hover:bg-slate-100 text-slate-700 font-semibold text-xs border border-slate-300 flex items-center justify-center gap-1.5 cursor-pointer shadow-xs"
            >
              <Download className="w-3.5 h-3.5" />
              Download .EML Draft
            </button>
            <button
              onClick={handleOpenOutlookMailto}
              className="flex-1 sm:flex-none px-5 py-2 rounded-lg bg-blue-600 hover:bg-blue-700 text-white font-semibold text-xs flex items-center justify-center gap-1.5 cursor-pointer shadow-sm transition-all"
            >
              <Send className="w-3.5 h-3.5" />
              Open in Outlook Client
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
